//! Sending statistics for the dashboard (`/api/overview`).

use anyhow::Result;
use ferropost_domain::overview::{Bucket, Counts};
use serde::Serialize;
use sqlx::PgPool;

/// Which sent mail to count.
#[derive(Debug, Clone, Default)]
pub struct Scope {
    pub campaign_id: Option<i64>,
    /// Sender domain.
    pub domain: Option<String>,
    /// Unix seconds, exclusive on both ends (as in Go).
    pub start: i64,
    pub end: i64,
}

/// Sent mail in scope with per-message outcome flags. `$1..$4` are the
/// scope; queries add their own parameters from `$5`.
///
/// Go joined `recipient_info` directly, which counted a message twice when
/// it had two recipient rows; `EXISTS` counts it once.
const SCOPED: &str = "
    WITH m AS (
        SELECT sm.postfix_message_id, sm.log_time_millis, sm.status, sm.mail_provider,
               sm.recipient, sm.dsn, sm.delay, sm.delays, sm.relay, sm.description, s.sender,
               (sm.status = 'sent' AND sm.dsn LIKE '2.%') AS ok,
               EXISTS (SELECT 1 FROM mailstat_opened o WHERE o.postfix_message_id = sm.postfix_message_id) AS opened,
               EXISTS (SELECT 1 FROM mailstat_clicked c WHERE c.postfix_message_id = sm.postfix_message_id) AS clicked
          FROM mailstat_send_mails sm
          JOIN mailstat_senders s ON s.postfix_message_id = sm.postfix_message_id
         WHERE sm.log_time_millis > $1 * 1000 AND sm.log_time_millis < $2 * 1000
           AND ($3::bigint IS NULL OR EXISTS (
                SELECT 1 FROM mailstat_message_ids mi
                  JOIN recipient_info r ON r.message_id = mi.message_id
                 WHERE mi.postfix_message_id = sm.postfix_message_id AND r.task_id = $3))
           AND ($4::text IS NULL OR lower(split_part(s.sender, '@', 2)) = lower($4))
    )";

const COUNTS: &str = "COUNT(*) AS sends,
    COUNT(*) FILTER (WHERE ok) AS delivered,
    COUNT(*) FILTER (WHERE status = 'bounced') AS bounced,
    COUNT(*) FILTER (WHERE opened) AS opened,
    COUNT(*) FILTER (WHERE clicked) AS clicked";

fn scoped<'q>(
    sql: &'q str,
    scope: &'q Scope,
) -> sqlx::query::QueryAs<'q, sqlx::Postgres, Counts, sqlx::postgres::PgArguments> {
    sqlx::query_as::<_, Counts>(sql)
        .bind(scope.start)
        .bind(scope.end)
        .bind(scope.campaign_id)
        .bind(scope.domain.as_deref())
}

pub async fn totals(pg: &PgPool, scope: &Scope) -> Result<Counts> {
    let sql = format!("{SCOPED} SELECT {COUNTS} FROM m");
    Ok(scoped(&sql, scope).fetch_one(pg).await?)
}

/// Counts per recipient provider, most sends first.
pub async fn by_provider(pg: &PgPool, scope: &Scope) -> Result<Vec<(String, Counts)>> {
    #[derive(sqlx::FromRow)]
    struct Row {
        mail_provider: String,
        #[sqlx(flatten)]
        counts: Counts,
    }
    let sql = format!(
        "{SCOPED} SELECT mail_provider, {COUNTS} FROM m GROUP BY mail_provider ORDER BY sends DESC, mail_provider"
    );
    let rows = sqlx::query_as::<_, Row>(&sql)
        .bind(scope.start)
        .bind(scope.end)
        .bind(scope.campaign_id)
        .bind(scope.domain.as_deref())
        .fetch_all(pg)
        .await?;
    Ok(rows
        .into_iter()
        .map(|r| (r.mail_provider, r.counts))
        .collect())
}

/// The time zone charts use: `tz` when PostgreSQL knows it, else UTC.
pub async fn chart_timezone(pg: &PgPool, tz: &str) -> Result<String> {
    let known: bool =
        sqlx::query_scalar("SELECT EXISTS (SELECT 1 FROM pg_timezone_names WHERE name = $1)")
            .bind(tz)
            .fetch_one(pg)
            .await?;
    Ok(if known {
        tz.to_owned()
    } else {
        "UTC".to_owned()
    })
}

/// Counts per bucket with empty buckets filled, in order. `x` is the hour
/// of day (0–23) for [`Bucket::Hour`], otherwise the Unix time the day or
/// month starts in `tz`. Buckets are generated by PostgreSQL in one time
/// zone, so months are calendar months and DST is handled; Go labelled in
/// the database zone, filled in the server zone and stepped months by 30
/// days.
pub async fn series(
    pg: &PgPool,
    scope: &Scope,
    bucket: Bucket,
    tz: &str,
) -> Result<Vec<(i64, Counts)>> {
    #[derive(sqlx::FromRow)]
    struct Row {
        x: i64,
        #[sqlx(flatten)]
        counts: Counts,
    }
    let local = "(to_timestamp(log_time_millis / 1000.0) AT TIME ZONE $5)";
    let sql = match bucket {
        Bucket::Hour => format!(
            "{SCOPED}, g AS (SELECT extract(hour FROM {local})::int AS h, {COUNTS} FROM m GROUP BY 1)
             SELECT h::bigint AS x, COALESCE(g.sends, 0) AS sends, COALESCE(g.delivered, 0) AS delivered,
                    COALESCE(g.bounced, 0) AS bounced, COALESCE(g.opened, 0) AS opened,
                    COALESCE(g.clicked, 0) AS clicked
               FROM generate_series(0, 23) AS h LEFT JOIN g USING (h)
              ORDER BY h"
        ),
        Bucket::Day | Bucket::Month => {
            let unit = bucket.sql_unit();
            format!(
                "{SCOPED},
                 b AS (SELECT generate_series(
                           date_trunc('{unit}', to_timestamp($1) AT TIME ZONE $5),
                           date_trunc('{unit}', to_timestamp($2) AT TIME ZONE $5),
                           interval '1 {unit}') AS bucket),
                 g AS (SELECT date_trunc('{unit}', {local}) AS bucket, {COUNTS} FROM m GROUP BY 1)
                 SELECT extract(epoch FROM (b.bucket AT TIME ZONE $5))::bigint AS x,
                        COALESCE(g.sends, 0) AS sends, COALESCE(g.delivered, 0) AS delivered,
                        COALESCE(g.bounced, 0) AS bounced, COALESCE(g.opened, 0) AS opened,
                        COALESCE(g.clicked, 0) AS clicked
                   FROM b LEFT JOIN g USING (bucket)
                  ORDER BY b.bucket"
            )
        }
    };
    let rows = sqlx::query_as::<_, Row>(&sql)
        .bind(scope.start)
        .bind(scope.end)
        .bind(scope.campaign_id)
        .bind(scope.domain.as_deref())
        .bind(tz)
        .fetch_all(pg)
        .await?;
    Ok(rows.into_iter().map(|r| (r.x, r.counts)).collect())
}

/// A delivery that did not succeed. `delay` and `log_time` are strings, as
/// Go's response struct converted them.
#[derive(Debug, Clone, PartialEq, Serialize, sqlx::FromRow)]
pub struct FailedDelivery {
    pub postfix_message_id: String,
    pub sender: String,
    pub recipient: String,
    pub status: String,
    pub dsn: String,
    pub relay: String,
    pub description: String,
    pub delay: String,
    pub delays: String,
    pub log_time: String,
}

/// Mail in scope whose status is not `sent`, newest first, with details of
/// the latest deferral when there was one.
pub async fn failed(pg: &PgPool, scope: &Scope) -> Result<Vec<FailedDelivery>> {
    let sql = format!(
        "{SCOPED}
         SELECT m.postfix_message_id, m.sender, m.recipient, m.status,
                COALESCE(d.dsn, m.dsn) AS dsn, COALESCE(d.relay, m.relay) AS relay,
                COALESCE(d.description, m.description) AS description,
                COALESCE(d.delay, m.delay)::text AS delay, COALESCE(d.delays, m.delays) AS delays,
                (m.log_time_millis / 1000)::text AS log_time
           FROM m
           LEFT JOIN LATERAL (
                SELECT dsn, delay, delays, relay, description FROM mailstat_deferred_mails
                 WHERE postfix_message_id = m.postfix_message_id ORDER BY id DESC LIMIT 1
           ) d ON true
          WHERE m.status <> 'sent'
          ORDER BY m.log_time_millis DESC"
    );
    Ok(sqlx::query_as::<_, FailedDelivery>(&sql)
        .bind(scope.start)
        .bind(scope.end)
        .bind(scope.campaign_id)
        .bind(scope.domain.as_deref())
        .fetch_all(pg)
        .await?)
}
