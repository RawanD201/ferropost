//! Email templates (`email_templates`) and the content checker.

use std::sync::LazyLock;

use regex::Regex;
use serde::Serialize;

/// A template as the console receives it. JSON names follow Go's
/// `v1.EmailTemplate` (`html_content`/`drag_data` for the columns
/// `content`/`render`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[cfg_attr(feature = "sqlx", derive(sqlx::FromRow))]
pub struct EmailTemplate {
    pub id: i32,
    pub temp_name: String,
    pub add_type: i16,
    #[serde(rename = "html_content")]
    pub content: String,
    #[serde(rename = "drag_data")]
    pub render: String,
    pub create_time: i32,
    pub update_time: i32,
    pub chat_id: String,
}

/// How a template was made (`add_type`).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TemplateKind {
    /// Uploaded or pasted HTML.
    Html = 0,
    /// Built in the drag-and-drop editor (HTML plus editor data).
    Drag = 1,
    /// Generated by the AI assistant.
    Ai = 2,
}

impl TemplateKind {
    pub fn from_code(code: i64) -> Option<Self> {
        match code {
            0 => Some(Self::Html),
            1 => Some(Self::Drag),
            2 => Some(Self::Ai),
            _ => None,
        }
    }

    pub fn code(self) -> i16 {
        self as i16
    }

    /// Checks the content a new template of this kind needs and returns the
    /// `(content, render)` to store. The error is Go's message.
    pub fn content<'a>(
        self,
        content: &'a str,
        render: &'a str,
    ) -> Result<(&'a str, &'a str), &'static str> {
        match self {
            Self::Html if content.is_empty() => Err("File data is required for upload type"),
            Self::Html => Ok((content, "")),
            Self::Drag if content.is_empty() || render.is_empty() => {
                Err("Content and render data are required for drag type")
            }
            Self::Drag => Ok((content, render)),
            Self::Ai => Ok((content, "")),
        }
    }
}

/// Name for a copy of `name`: `<name>_bak`, then `<name>_bak_2`, ...
pub fn copy_name(name: &str, attempt: u32) -> String {
    match attempt {
        0 | 1 => format!("{name}_bak"),
        n => format!("{name}_bak_{n}"),
    }
}

