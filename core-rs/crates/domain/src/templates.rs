/// HTML elements that never have a closing tag.
const VOID_ELEMENTS: &[&str] = &[
    "area", "base", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "track",
    "wbr",
];

fn regex(pattern: &str) -> Regex {
    Regex::new(pattern).expect("static pattern")
}

static OPEN_TAG: LazyLock<Regex> = LazyLock::new(|| regex(r"<([a-zA-Z]+)[^>]*?(/?)>"));
static CLOSE_TAG: LazyLock<Regex> = LazyLock::new(|| regex(r"</([a-zA-Z]+)>"));
static IMG_TAG: LazyLock<Regex> = LazyLock::new(|| regex(r"<img[^>]*?>"));
static ANY_TAG: LazyLock<Regex> = LazyLock::new(|| regex(r"<.*?>"));
static ALT_ATTR: LazyLock<Regex> = LazyLock::new(|| regex(r#"alt\s*=\s*['"]"#));

/// Every non-void element opened is closed the same number of times. Go
/// also counted `<br>` and `<img>`, so nearly every email failed.
fn html_balanced(content: &str) -> bool {
    let mut open = std::collections::HashMap::<String, i64>::new();
    for cap in OPEN_TAG.captures_iter(content) {
        let tag = cap[1].to_ascii_lowercase();
        if VOID_ELEMENTS.contains(&tag.as_str()) || &cap[2] == "/" {
            continue;
        }
        *open.entry(tag).or_default() += 1;
    }
    for cap in CLOSE_TAG.captures_iter(content) {
        *open.entry(cap[1].to_ascii_lowercase()).or_default() -= 1;
    }
    open.values().all(|n| *n == 0)
}

fn image_only(content: &str) -> bool {
    IMG_TAG.is_match(content) && ANY_TAG.replace_all(content, "").trim().len() < 10
}

fn images_without_alt(content: &str) -> usize {
    IMG_TAG
        .find_iter(content)
        .filter(|img| !ALT_ATTR.is_match(img.as_str()))
        .count()
}

/// Deliverability score out of 10 with the reasons for each deduction
/// (Go's `CheckEmailContent`).
pub fn check_content(content: &str) -> ContentScore {
    let mut items = Vec::new();
    let mut deduct = |name: &str, detail: String, score: f64| {
        items.push(ScoreItem {
            name: name.to_owned(),
            detail,
            score,
        });
    };

    let lower = content.to_lowercase();
    for word in SPAM_WORDS.iter().filter(|w| lower.contains(*w)) {
        deduct("Spam Word", format!("Contains spam word: {word}"), -1.0);
    }
    if !html_balanced(content) {
        deduct("HTML Format", "HTML tags are not standard".into(), -0.5);
    }
    if image_only(content) {
        deduct(
            "Image Ratio",
            "Content is purely images or image-heavy".into(),
            -1.0,
        );
    }
    let missing_alt = images_without_alt(content);
    if missing_alt > 0 {
        let penalty = -0.2 * missing_alt as f64;
        deduct(
            "Missing Alt Attribute",
            format!("{missing_alt} <img> tags are missing the alt attribute"),
            penalty,
        );
    }
    if SHORT_LINK_DOMAINS.iter().any(|d| content.contains(d)) {
        deduct("Short Link", "Contains a short link domain".into(), -0.5);
    }

    let score = items
        .iter()
        .fold(10.0, |total, item| total + item.score)
        .max(0.0);
    ContentScore { score, items }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn kinds_require_their_content() {
        assert_eq!(
            TemplateKind::Html.content("<p>x</p>", "r"),
            Ok(("<p>x</p>", ""))
        );
        assert!(TemplateKind::Html.content("", "").is_err());
        assert!(TemplateKind::Drag.content("<p>x</p>", "").is_err());
        assert_eq!(TemplateKind::Drag.content("h", "r"), Ok(("h", "r")));
        assert_eq!(TemplateKind::Ai.content("", "r"), Ok(("", "")));
        assert_eq!(TemplateKind::from_code(3), None);
    }

    #[test]
    fn copy_names() {
        assert_eq!(copy_name("Welcome", 1), "Welcome_bak");
        assert_eq!(copy_name("Welcome", 3), "Welcome_bak_3");
    }

    #[test]
    fn clean_email_scores_ten() {
        let html = r#"<html><body><p>Hello there,<br>our monthly update.</p><img src="a.png" alt="logo"></body></html>"#;
        let score = check_content(html);
        assert_eq!(score.items, vec![]);
        assert_eq!(score.score, 10.0);
    }

    #[test]
    fn deductions_match_go_rules() {
        let html =
            r#"<div><p>FREE offer, click here: bit.ly/x</p><img src="a"><img src="b"></div><span>"#;
        let score = check_content(html);
        let names: Vec<&str> = score.items.iter().map(|i| i.name.as_str()).collect();
        assert_eq!(
            names,
            [
                "Spam Word",
                "Spam Word",
                "HTML Format",
                "Missing Alt Attribute",
                "Short Link"
            ]
        );
        assert_eq!(score.items[0].detail, "Contains spam word: free");
        assert_eq!(
            score.items[3].detail,
            "2 <img> tags are missing the alt attribute"
        );
        assert!((score.score - 6.6).abs() < 1e-9);
    }

    #[test]
    fn image_only_and_floor() {
        assert!(image_only(r#"<img src="banner.png" alt="x">hi"#));
        assert!(!image_only("<p>A real paragraph of text</p>"));
        let spammy = SPAM_WORDS.join(" ");
        assert_eq!(check_content(&spammy).score, 0.0);
    }

    #[test]
    fn serialises_with_go_names() {
        let t = EmailTemplate {
            id: 1,
            temp_name: "w".into(),
            add_type: 1,
            content: "<p/>".into(),
            render: "{}".into(),
            create_time: 1,
            update_time: 2,
            chat_id: String::new(),
        };
        let json = serde_json::to_value(&t).expect("json");
        assert_eq!(json["html_content"], "<p/>");
        assert_eq!(json["drag_data"], "{}");
        assert!(json.get("content").is_none());
    }
}
